# The lane-use arrows painted on Ann Arbor's approaches to its junctions, from OpenStreetMap's turn:lanes tags (ODbL),
# in the game's frame (metres east and south of Main St & Liberty St), written to Web/js/turn-lanes-data.js for
# road-paint.js:
#   TURN_LANES  [[x, z, dx, dz, lane, lane, ...], ...]  one per tagged approach: where the way ends going the way it's
#               driven (x, z), its direction over its last 15 m (dx, dz), and each lane's turns from the left (bits:
#               1 left, 2 through, 4 right; 'none' is through). Only approaches with a turn in some lane.
# Input: .lamp/reference/aa/osm.json. Run: python3 -I Assets/Tools/build-turn-lanes.py <app folder holding .lamp>
import json, math, os, sys

ROOT = sys.argv[1]
LAT0, LON0 = 42.27965, -83.74838
A, E2 = 6378137.0, 6.69437999014e-3
phi = math.radians(LAT0)
KX = math.pi / 180 * A / math.sqrt(1 - E2 * math.sin(phi) ** 2) * math.cos(phi)
KY = math.pi / 180 * A * (1 - E2) / (1 - E2 * math.sin(phi) ** 2) ** 1.5
xz = lambda lon, lat: ((lon - LON0) * KX, -(lat - LAT0) * KY)
DRIVE = {'motorway_link', 'trunk', 'trunk_link', 'primary', 'primary_link', 'secondary', 'secondary_link', 'tertiary',
         'tertiary_link', 'residential', 'unclassified'}


def code(v):
    c = 0
    for p in v.split(';'):
        p = p.strip()
        c |= 1 if p in ('left', 'slight_left', 'sharp_left') else 4 if p in ('right', 'slight_right', 'sharp_right') \
            else 2 if p in ('through', 'none', '') else 0
    return c or 2


def approach(pts, turns):
    lanes = [code(v) for v in turns.split('|')]
    if not any(c & 5 for c in lanes):
        return None
    x1, z1 = pts[-1]
    # the direction over the last 15 m
    k, run = len(pts) - 1, 0.0
    while k > 0 and run < 15:
        run += math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1])
        k -= 1
    x0, z0 = pts[k]
    L = math.hypot(x1 - x0, z1 - z0)
    if L < 3:
        return None
    return [round(x1, 1), round(z1, 1), round((x1 - x0) / L, 3), round((z1 - z0) / L, 3)] + lanes


els = json.load(open(os.path.join(ROOT, '.lamp/reference/aa/osm.json')))['elements']
out = []
for e in els:
    t = e.get('tags') or {}
    if e['type'] != 'way' or t.get('highway') not in DRIVE or not e.get('geometry'):
        continue
    pts = [xz(g['lon'], g['lat']) for g in e['geometry']]
    oneway = t.get('oneway') in ('yes', '1', 'true') or t.get('junction') == 'roundabout' or t.get('highway', '').endswith('_link')
    if t.get('oneway') == '-1':
        pts, oneway = pts[::-1], True
    fwd = t.get('turn:lanes') if oneway else t.get('turn:lanes:forward')
    for turns, p in ((fwd, pts), (None if oneway else t.get('turn:lanes:backward'), pts[::-1])):
        a = turns and approach(p, turns)
        if a:
            out.append(a)
out.sort()
path = os.path.join(os.path.dirname(__file__), '../../Web/js/turn-lanes-data.js')
with open(path, 'w') as f:
    f.write('// Generated by Assets/Tools/build-turn-lanes.py from OpenStreetMap (ODbL); do not edit.\n')
    f.write("// Lane-use arrows: [[x, z, dx, dz, lane...], ...], lanes from the left, bits 1 left 2 through 4 right\n")
    f.write('export const TURN_LANES = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'approaches with turn lanes')
