# Ann Arbor's brick streets (Detroit St and N Fourth and Fifth Aves by Kerrytown, Kingsley, First, Carey and the
# rest OpenStreetMap tags surface=paving_stones / sett / bricks), in the game's frame (metres east and south of Main St
# & Liberty St), written to Web/js/brick-streets-data.js for brick-streets.js:
#   BRICK_STREETS  [[name, x, z, x, z, ...], ...]  each such way's centre line (OSM ODbL), streets only (no paths,
#                  sidewalks, alleys or parking aisles); the roadway's width is the game's own street's (GEO.roads)
# Input: .lamp/reference/aa/osm.json. Run: python3 -I Assets/Tools/build-brick-streets.py <app folder holding .lamp>
import json, math, os, sys

ROOT = sys.argv[1]
LAT0, LON0 = 42.27965, -83.74838
A, E2 = 6378137.0, 6.69437999014e-3
phi = math.radians(LAT0)
KX = math.pi / 180 * A / math.sqrt(1 - E2 * math.sin(phi) ** 2) * math.cos(phi)
KY = math.pi / 180 * A * (1 - E2) / (1 - E2 * math.sin(phi) ** 2) ** 1.5
xz = lambda lon, lat: ((lon - LON0) * KX, -(lat - LAT0) * KY)
BRICK = {'paving_stones', 'sett', 'bricks', 'brick', 'cobblestone', 'unhewn_cobblestone'}
STREETS = {'primary', 'secondary', 'tertiary', 'residential', 'unclassified', 'living_street', 'primary_link',
           'secondary_link', 'tertiary_link'}

els = json.load(open(os.path.join(ROOT, '.lamp/reference/aa/osm.json')))['elements']
ways = []
for e in els:
    t = e.get('tags') or {}
    if e['type'] != 'way' or t.get('highway') not in STREETS or t.get('surface') not in BRICK or not e.get('geometry'):
        continue
    pts = []
    for g in e['geometry']:
        x, z = xz(g['lon'], g['lat'])
        pts += [round(x, 1), round(z, 1)]
    ways.append([t.get('name') or '', *pts])
ways.sort(key=lambda w: (w[0], w[1], w[2]))
out = os.path.join(os.path.dirname(__file__), '../../Web/js/brick-streets-data.js')
with open(out, 'w') as f:
    f.write('// Generated by Assets/Tools/build-brick-streets.py from OpenStreetMap (ODbL); do not edit.\n')
    f.write("// Ann Arbor's brick streets: [[name, x, z, x, z, ...], ...] (metres east and south of Main St & Liberty St)\n")
    f.write('export const BRICK_STREETS = ' + json.dumps(ways, separators=(',', ':')) + ';\n')
print(len(ways), 'brick street ways:', sorted({w[0] for w in ways}))
