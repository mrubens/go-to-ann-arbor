# Ann Arbor's roundabouts (OpenStreetMap ways tagged junction=roundabout, ODbL): each ring's centre and the radius of
# its circulating roadway's centre line at its nearest, for roundabouts.js (the central island and its apron) and road-network.js
# (traffic circling the island). Ways of one ring are joined by shared nodes; service-road and parking-lot rings and
# rings too small (a painted mini roundabout) or too big to be one are left out. Written to Web/js/roundabout-data.js:
#   ROUNDABOUTS  flat [x, z, r, ...]  (metres east and south of Main St & Liberty St)
# Input: .lamp/reference/aa/osm.json. Run: python3 -I Assets/Tools/build-roundabouts.py <app folder> [cache folder]
import json, math, os, sys

ROOT = sys.argv[1]
CACHE = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, '.lamp/reference/aa')
LAT0, LON0 = 42.27965, -83.74838
A, E2 = 6378137.0, 6.69437999014e-3
phi = math.radians(LAT0)
KX = math.pi / 180 * A / math.sqrt(1 - E2 * math.sin(phi) ** 2) * math.cos(phi)
KY = math.pi / 180 * A * (1 - E2) / (1 - E2 * math.sin(phi) ** 2) ** 1.5
xz = lambda lon, lat: ((lon - LON0) * KX, -(lat - LAT0) * KY)

osm = json.load(open(os.path.join(CACHE, 'osm.json')))['elements']
ways = [e for e in osm if e['type'] == 'way' and e.get('tags', {}).get('junction') in ('roundabout', 'circular')
        and e.get('tags', {}).get('highway') not in (None, 'service', 'footway', 'cycleway', 'path')
        and len(e.get('geometry') or []) >= 2]
# group the ways into rings by shared nodes
parent = list(range(len(ways)))
def find(i):
    while parent[i] != i:
        parent[i] = parent[parent[i]]
        i = parent[i]
    return i
by_node = {}
for i, w in enumerate(ways):
    for n in w.get('nodes', []):
        if n in by_node:
            parent[find(i)] = find(by_node[n])
        else:
            by_node[n] = i
rings = {}
for i, w in enumerate(ways):
    rings.setdefault(find(i), []).extend(xz(p['lon'], p['lat']) for p in w['geometry'])
out = []
for pts in rings.values():
    cx = sum(p[0] for p in pts) / len(pts)
    cz = sum(p[1] for p in pts) / len(pts)
    ds = [math.hypot(p[0] - cx, p[1] - cz) for p in pts]
    r = sum(ds) / len(ds)
    # a ring: its points all round the centre (an oval one too, as Earhart's at Glazier Way), the size of a real
    # roundabout's; its nearest point's radius kept, so a round island inside it never reaches the lanes
    if not 7 <= r <= 40 or min(ds) < 5.5 or max(ds) - min(ds) > 0.8 * r:
        continue
    out += [round(cx, 1), round(cz, 1), round(min(ds), 1)]
dst = os.path.join(ROOT, 'Web/js/roundabout-data.js')
with open(dst, 'w') as f:
    f.write('// Generated by Assets/Tools/build-roundabouts.py from OpenStreetMap (ODbL); do not edit.\n')
    f.write("// Roundabouts: flat [x, z, r, ...], each ring's centre and its circulating roadway's centre line's nearest radius (m)\n")
    f.write('export const ROUNDABOUTS = ' + json.dumps(out) + ';\n')
print(f'{dst}: {len(out) // 3} roundabouts')
