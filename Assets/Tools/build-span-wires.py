# Which of Ann Arbor's traffic lights hang from span wires: the ones on the state's routes through town (the business
# loops I-94 BL and US-23 BUS, M-17, US-12: OpenStreetMap ways with a ref, ODbL) outside the downtown core and central
# campus, which MDOT signals with wires strung corner to corner (Huron at Fifth and First, N Main at Ann and Kingsley,
# Washtenaw at Hill, Geddes and by Arborland); the city's own streets and downtown have mast arms or posts. Written to
# Web/js/span-wire-data.js for traffic-controls.js:
#   SPAN_WIRES  flat [x, z, ...]  each such light (metres east and south of Main St & Liberty St)
# Input: .lamp/reference/aa/osm.json and sig/osm_signals.json. Run: python3 -I Assets/Tools/build-span-wires.py <app folder>
import json, math, os, sys

ROOT = sys.argv[1]
LAT0, LON0 = 42.27965, -83.74838
A, E2 = 6378137.0, 6.69437999014e-3
phi = math.radians(LAT0)
KX = math.pi / 180 * A / math.sqrt(1 - E2 * math.sin(phi) ** 2) * math.cos(phi)
KY = math.pi / 180 * A * (1 - E2) / (1 - E2 * math.sin(phi) ** 2) ** 1.5
xz = lambda lon, lat: ((lon - LON0) * KX, -(lat - LAT0) * KY)
# the downtown core and central campus (as utility-poles.js UNDERGROUND), x east and z south, m
CORE = [(-300, 700, -170, 300), (700, 1450, -250, 820), (-120, 420, 1250, 1900)]
in_core = lambda x, z: any(x0 < x < x1 and z0 < z < z1 for x0, x1, z0, z1 in CORE)

REF = os.path.join(ROOT, '.lamp/reference/aa')
segs = []
for e in json.load(open(os.path.join(REF, 'osm.json')))['elements']:
    t = e.get('tags') or {}
    if e['type'] != 'way' or not t.get('ref') or t.get('highway') not in ('trunk', 'primary', 'secondary', 'tertiary') \
            or not e.get('geometry'):
        continue
    p = [xz(g['lon'], g['lat']) for g in e['geometry']]
    segs += list(zip(p, p[1:]))


def dist(x, z, a, b):
    ex, ez = b[0] - a[0], b[1] - a[1]
    t = max(0, min(1, ((x - a[0]) * ex + (z - a[1]) * ez) / (ex * ex + ez * ez or 1)))
    return math.hypot(a[0] + ex * t - x, a[1] + ez * t - z)


out = []
for e in json.load(open(os.path.join(REF, 'sig/osm_signals.json')))['elements']:
    if (e.get('tags') or {}).get('highway') != 'traffic_signals' or 'lat' not in e:
        continue
    x, z = xz(e['lon'], e['lat'])
    if in_core(x, z) or not any(dist(x, z, a, b) < 12 for a, b in segs):
        continue
    out += [round(x, 1), round(z, 1)]
path = os.path.join(os.path.dirname(__file__), '../../Web/js/span-wire-data.js')
with open(path, 'w') as f:
    f.write('// Generated by Assets/Tools/build-span-wires.py from OpenStreetMap (ODbL); do not edit.\n')
    f.write('// Traffic lights hung from span wires (the state routes outside downtown): flat [x, z, ...]\n')
    f.write('export const SPAN_WIRES = ' + json.dumps(out) + ';\n')
print(len(out) // 2, 'lights on span wires')
